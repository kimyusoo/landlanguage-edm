function series(base: number, step: number, n = 8): { date: string; value: number }[] {
  const out: { date: string; value: number }[] = [];
  const start = new Date("2026-07-14T00:00:00+09:00");
  for (let i = 0; i < n; i++) {
    const d = new Date(start.getTime() + i * 7 * 86400000);
    out.push({
      date: d.toISOString().slice(0, 10),
      value: Number((base + step * i + (i % 2 === 0 ? 0.01 : -0.01)).toFixed(3)),
    });
  }
  return out;
}

